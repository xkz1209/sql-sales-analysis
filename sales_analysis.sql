===============================================================================
Customer Report
===============================================================================
Purpose:
    - This report consolidates key customer metrics and behaviors

Highlights:
    1. Gathers essential fields such as names, ages, and transaction details.
    2. Segments customers into categories (VIP, Regular, New) and age groups.
    3. Aggregates customer-level metrics:
        - total orders
        - total sales
        - total quantity purchased
        - total products
        - lifespan (in months)
    4. Calculates valuable KPIs:
        - recency (months since last order)
        - average order value
        - average monthly spend
===============================================================================
*/
-- 1. Base Query: Retrieves core columns from tables
GO
CREATE VIEW gold.report_customers AS
WITH base_query as (
SELECT
f.order_number ,
f.product_key,
f.order_date,
f.sales_amount,
f.quantity,
c.customer_key,
c.customer_number,
CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
DATEDIFF(year, c.birthdate, GETDATE() ) as age
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
WHERE order_date IS NOT NULL
), customer_aggreagation as(
 --  2. Segments customers into categories (VIP, Regular, New) and age groups.
SELECT 
customer_key,
customer_number,
customer_name,
age,
COUNT(DISTINCT order_number) as total_orders,
SUM(sales_amount) as total_sales,
SUM(quantity) as total_quantity,
COUNT(DISTINCT product_key) as total_products,
MAX(order_date) as last_order_date,
DATEDIFF(month, MIN(order_date), MAX(order_date)) as life_span
FROM
base_query
GROUP BY
customer_key,
customer_number,
customer_name,
age)
--  3. Aggregates customer-level metrics:
SELECT
customer_key,
customer_number,
customer_name,
age,
CASE WHEN age < 20 THEN 'Under 20'
	 WHEN age between 20 and 29 THEN '20-29'
	 WHEN age between 30 and 39 THEN '30-39'
	 WHEN age between 40 and 40 THEN '40-49'
ELSE '50 and above'
END AS age_group,
CASE WHEN life_span >= 12 AND total_sales > 5000 THEN 'VIP'
		 WHEN life_span >= 12 AND total_sales <= 5000 THEN 'Regular'
		 ELSE 'NEW'
	END AS customer_segement,
last_order_date,
/*
 4. Calculates valuable KPIs:
        - recency (months since last order)
        - average order value (total sales / total number of orders)
        - average monthly spend
*/

DATEDIFF(month,last_order_date,GETDATE()) as recency,
total_orders,
total_sales,
total_quantity,
total_products,
life_span,
-- computer average order value (AVO)
CASE WHEN total_sales = 0 THEN 0 
	 ELSE total_sales / total_orders 
END AS avg_order_value,
--computer average monthly spend(total sales / number of months)
CASE WHEN life_span = 0 THEN total_sales 
	 ELSE total_sales / life_span
END AS avg_monthly_spend
FROM customer_aggreagation

