-- Performance Analysis
/* Analyze the yearly performance of products by comparing their sales
to both the average sales performance of the product and the previous year's sales */

WITH yearly_product_sales AS (
SELECT 
YEAR(f.order_date) AS order_year,
p.product_name,
SUM(f.sales_amount) AS current_sales
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON f.product_key = p.product_key
WHERE f.order_date IS NOT NULL
GROUP BY
YEAR(f.order_date),
p.product_name
)

SELECT 
order_year,
product_name,
current_sales,
AVG (current_sales) OVER (PARTITION BY product_name) as avg_sales,
current_sales - AVG (current_sales)  OVER (PARTITION BY product_name) as diff_avg,
CASE WHEN current_sales - AVG (current_sales)  OVER (PARTITION BY product_name) IS NULL THEN 'N/A'
	WHEN current_sales - AVG (current_sales)  OVER (PARTITION BY product_name) > 0 THEN 'Above Avg'
	WHEN current_sales - AVG (current_sales)  OVER (PARTITION BY product_name) < 0 THEN 'Below Avg'
	ELSE 'AVG'
END AS avg_change,
-- year over year analysis
LAG(current_sales) OVER (PARTITION BY product_name ORDER BY order_year)  AS previous_year_sales ,
current_sales - LAG(current_sales) OVER (PARTITION BY product_name ORDER BY order_year) AS diff_betwe_pervious_year,
CASE WHEN current_sales - LAG(current_sales) OVER (PARTITION BY product_name ORDER BY order_year) IS NULL THEN 'N/A'
	WHEN current_sales - LAG(current_sales) OVER (PARTITION BY product_name ORDER BY order_year) > 0 THEN 'Increase'
	WHEN current_sales -LAG(current_sales) OVER (PARTITION BY product_name ORDER BY order_year) < 0 THEN 'Decrease'
	ELSE 'No Change'
END AS previous_year_change
FROM yearly_product_sales
ORDER BY product_name, order_year	


